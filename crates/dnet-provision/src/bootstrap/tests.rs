#[test]
fn a_report_in_the_wrong_shape_is_refused_without_quoting_it() {
    type Edit = Box<dyn FnOnce(&mut serde_json::Value)>;
    let cases: Vec<Edit> = vec![
        Box::new(|j| j["hysteria2"]["server_port"] = serde_json::json!(SENTINEL)),
        Box::new(|j| j["hysteria2"]["auth_password"] = serde_json::json!(12345)),
        Box::new(|j| j["extra"] = serde_json::json!(SENTINEL)),
        Box::new(|j| {
            j["reality"].as_object_mut().unwrap().remove("uuid");
        }),
        Box::new(|j| j["hysteria2"]["surprise"] = serde_json::json!(SENTINEL)),
    ];
    for edit in cases {
        let error = parse(edit).unwrap_err();
        assert!(matches!(error, ReportError::Malformed(_)), "{error:?}");
        assert!(!error.to_string().contains("SENTINEL"), "{error}");
    }
    let not_json = BootstrapReport::parse(&format!("{REPORT_PREFIX}{{{SENTINEL}")).unwrap_err();
    assert!(!not_json.to_string().contains("SENTINEL"), "{not_json}");
}

