#[test]
fn a_value_with_shell_syntax_in_it_is_refused_in_every_field_before_any_text_is_made() {
    let hostile = [
        "x'; rm -rf / #",
        "x$(id)",
        "x`id`",
        "x y",
        "x\nid",
        "x;id",
        "x|id",
        "x&id",
        "x>y",
        "x\"y",
        "x\\y",
        "x*",
    ];
    for bad in hostile.into_iter().chain(std::iter::once("")) {
        if !bad.is_empty() {
            let mut p = plan();
            p.cores.primary_core.url = format!("https://example.test/{bad}");
            assert!(script(&p).is_err(), "url {bad:?}");
        }

        let mut p = plan();
        p.cores.primary_core.version = bad.to_owned();
        assert!(script(&p).is_err(), "version {bad:?}");

        let mut p = plan();
        p.cores.amneziawg.licence = bad.to_owned();
        assert!(script(&p).is_err(), "licence {bad:?}");

        let mut p = plan();
        p.cores.amneziawg.source = bad.to_owned();
        assert!(script(&p).is_err(), "source {bad:?}");

        let mut p = plan();
        p.cores.amneziawg.name = bad.to_owned();
        assert!(script(&p).is_err(), "name {bad:?}");

        let mut p = plan();
        p.hysteria2_server_name = bad.to_owned();
        assert!(script(&p).is_err(), "server name {bad:?}");

        let mut p = plan();
        p.awg_client_public_hex = bad.to_owned();
        assert!(script(&p).is_err(), "client key {bad:?}");
    }
}

