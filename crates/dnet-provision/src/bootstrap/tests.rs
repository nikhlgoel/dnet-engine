#[test]
fn each_core_is_checked_against_its_pin_before_it_is_made_executable() {
    let text = script(&plan()).unwrap();
    let verify = text
        .find("sha256sum \"$tmp\"")
        .expect("the download is hashed");
    let chmod = text
        .find("chmod 0755 \"$tmp\"")
        .expect("then made executable");
    let mv = text
        .find("mv \"$tmp\" \"$4\"")
        .expect("then moved into place");
    assert!(
        verify < chmod && chmod < mv,
        "the order must be hash, chmod, move"
    );
    assert!(text.contains("exit 4"), "a mismatch must stop everything");
    assert!(
        text.contains("--proto '=https'"),
        "downloads are https only"
    );
    assert_eq!(
        text.matches("\nfetch ").count(),
        2,
        "exactly the two cores are fetched"
    );
}

#[test]
fn the_script_contains_no_secret_and_no_private_key() {
    let text = script(&plan()).unwrap();
    assert!(!text.contains("BEGIN PRIVATE KEY"));
    assert!(!text.contains("BEGIN EC PRIVATE KEY"));
    // Every 64-digit hex string in it is a pin or the client's public key, and nothing else.
    let allowed = ["a".repeat(64), "b".repeat(64), "c".repeat(64)];
    for word in text.split(|c: char| !c.is_ascii_hexdigit()) {
        if word.len() == 64 {
            assert!(
                allowed.contains(&word.to_owned()),
                "an unexpected key-sized value: {word}"
            );
        }
    }
    // The client's private key is not even an input: the plan only has room for the public half.
    assert!(!text.contains("client_private") && !text.contains("CLIENT_PRIV"));
}

#[test]
fn the_certificate_is_ecdsa_and_the_script_refuses_to_finish_with_anything_else() {
    let text = script(&plan()).unwrap();
    assert!(text.contains("openssl ecparam -name prime256v1 -genkey"));
    assert!(text.contains("never Ed25519"));
    let guard = text
        .find("*) echo \"the Hysteria 2 certificate must be ECDSA or RSA")
        .unwrap();
    let report = text.find("DNET-BOOTSTRAP-REPORT").unwrap();
    assert!(
        guard < report,
        "the check comes before anything is reported"
    );
    // No Ed25519 key is ever generated by the script.
    let lower = text.to_ascii_lowercase();
    assert!(!lower.contains("-algorithm ed25519"));
}

#[test]
fn every_key_and_secret_is_made_only_when_its_file_is_missing() {
    let text = script(&plan()).unwrap();
    for (generator, guard) in [
        (
            "openssl genpkey -algorithm X25519",
            "[ ! -s \"$STATE/awg/server.pem\" ]",
        ),
        (
            "openssl rand -hex 16",
            "[ ! -s \"$STATE/primary/$secret.secret\" ]",
        ),
        (
            "openssl ecparam -name prime256v1",
            "[ ! -s \"$STATE/primary/server.key\" ]",
        ),
        (
            "generate reality-keypair",
            "[ ! -s \"$STATE/primary/reality.private\" ]",
        ),
        ("generate uuid", "[ -s \"$STATE/primary/uuid\" ]"),
        (
            "generate rand --hex 8",
            "[ -s \"$STATE/primary/short_id\" ]",
        ),
    ] {
        let at = text
            .find(generator)
            .unwrap_or_else(|| panic!("no {generator}"));
        let guard_at = text[..at]
            .rfind(guard)
            .unwrap_or_else(|| panic!("{generator} is not guarded by {guard}"));
        assert!(at - guard_at < 400, "{generator} is too far from its guard");
    }
    // The server configuration is written only if absent, so a re-run cannot change a running server.
    assert!(text.contains("if [ ! -s \"$STATE/primary/server.json\" ]; then"));
    // Nothing deletes state.
    assert!(!text.contains("rm -rf"));
    assert!(!text.contains("rm -r "));
    assert!(!text.contains("> \"$STATE/awg/server.pem\""));
}

