#[test]
fn the_credentials_carry_what_the_server_reported_and_the_clients_own_key() {
    let keys = ClientKeys::from_private([7u8; 32]);
    let report = parse(|_| {}).unwrap();
    let origin = Origin::parse("http://203.0.113.80:8080").ok();
    let creds = report.credentials(&keys, plan().obfuscation, origin.clone());

    let awg = creds.amneziawg.as_ref().unwrap();
    assert_eq!(awg.client_private_key.expose_wire(), keys.private_hex());
    assert_eq!(awg.server_public_key, "d".repeat(64));
    assert_eq!(awg.client_address, TUNNEL_CLIENT);
    assert_eq!(awg.server_port, 51820);
    assert_eq!(awg.obfuscation, plan().obfuscation);

    let hy2 = creds.hysteria2.as_ref().unwrap();
    assert_eq!(hy2.server_port, 44443);
    assert!(matches!(
        hy2.endpoint.trust,
        ServerTrust::PinnedPublicKey { spki_sha256, .. } if spki_sha256 == [0xee; 32]
    ));
    assert!(matches!(hy2.endpoint.obfs, Hysteria2Obfs::Salamander));

    let reality = creds.reality.as_ref().unwrap();
    assert_eq!(reality.server_port, 8443);
    assert_eq!(reality.endpoint.target_domain.as_str(), "www.example.com");

    assert_eq!(creds.measure_origin, origin);
    // The set is one the daemon's store would accept.
    assert!(creds.to_plaintext_json().is_ok());
}

