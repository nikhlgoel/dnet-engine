fn output_with(report: &serde_json::Value) -> String {
    format!(
        "installing...\nok\n{REPORT_PREFIX}{}\ndone\n",
        serde_json::to_string(report).unwrap()
    )
}

fn parse(edit: impl FnOnce(&mut serde_json::Value)) -> Result<BootstrapReport, ReportError> {
    let mut json = report_json();
    edit(&mut json);
    BootstrapReport::parse(&output_with(&json))
}

