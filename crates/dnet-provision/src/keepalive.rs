//! T094 — keep the provider from reclaiming an idle machine (FR-013, PR-15's stage, PRV-09, research R10).
//!
//! Free cloud compute is lent on condition that it is used. A machine that does nothing for long enough is
//! taken back, with its address, and the person's endpoint silently stops existing. An endpoint is idle by
//! nature, since it only moves traffic when someone is connected, so provisioning has to install something
//! that keeps it from looking unused, and has to **fail the job if that is not in place**: an endpoint that
//! works today and disappears in a week is worse than one that was never made.
//!
//! The provider's published rule at the time of writing is on utilisation over a week (a high percentile of
//! CPU, among other measures, must exceed a threshold). What is done here is deliberately not tuned to the
//! edge of any such rule: a short burst of work at regular intervals, busy for roughly a tenth of the time,
//! so that the busy samples are far more than the few percent a high percentile looks at. The real
//! requirement is a property of the provider, not of this crate, and it changes; whether a machine survives
//! is checked against a real instance (T098: "survives idle reclamation"), not here.
//!
//! The work is a counter loop at the lowest scheduling priority. It does no network traffic, writes nothing,
//! and gives way to the transports the moment they need the CPU.

/// The command a provider runs on the machine to learn whether the keepalive is installed and scheduled.
/// Exit status 0 means yes.
pub const CHECK_COMMAND: &str = "systemctl is-active --quiet dnet-keepalive.timer";

/// Shortest burst that is worth scheduling, in seconds: shorter than a utilisation sample.
pub const MIN_BURST_SECS: u32 = 60;
/// Longest gap between bursts, in seconds.
pub const MAX_PERIOD_SECS: u32 = 3600;
/// The least share of time spent busy that is accepted, in percent. Well above the few percent that a
/// high-percentile rule looks at.
pub const MIN_DUTY_PERCENT: u32 = 8;
/// The most share of time spent busy that is accepted, in percent. The machine is there to carry traffic.
pub const MAX_DUTY_PERCENT: u32 = 50;

/// How the keepalive is scheduled.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct KeepalivePlan {
    burst_secs: u32,
    period_secs: u32,
}

/// Why a schedule was refused.
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
pub enum KeepaliveError {
    #[error("a burst must last at least {MIN_BURST_SECS} seconds")]
    BurstTooShort,
    #[error("bursts must come at least every {MAX_PERIOD_SECS} seconds")]
    PeriodTooLong,
    #[error(
        "the busy share must be between {MIN_DUTY_PERCENT}% and {MAX_DUTY_PERCENT}% of the time"
    )]
    DutyOutOfRange,
}

impl KeepalivePlan {
    pub fn new(burst_secs: u32, period_secs: u32) -> Result<Self, KeepaliveError> {
        if burst_secs < MIN_BURST_SECS {
            return Err(KeepaliveError::BurstTooShort);
        }
        if period_secs > MAX_PERIOD_SECS {
            return Err(KeepaliveError::PeriodTooLong);
        }
        // Integer percent of a period spent busy; a burst longer than its period is over 100%.
        let duty = u64::from(burst_secs) * 100 / u64::from(period_secs.max(1));
        if !(u64::from(MIN_DUTY_PERCENT)..=u64::from(MAX_DUTY_PERCENT)).contains(&duty) {
            return Err(KeepaliveError::DutyOutOfRange);
        }
        Ok(Self {
            burst_secs,
            period_secs,
        })
    }

    pub fn burst_secs(&self) -> u32 {
        self.burst_secs
    }

    pub fn period_secs(&self) -> u32 {
        self.period_secs
    }

    /// Percent of time spent busy.
    pub fn duty_percent(&self) -> u32 {
        (u64::from(self.burst_secs) * 100 / u64::from(self.period_secs)) as u32
    }
}

impl Default for KeepalivePlan {
    /// Four minutes of work every forty: about a tenth of the time.
    fn default() -> Self {
        Self {
            burst_secs: 240,
            period_secs: 2400,
        }
    }
}

/// The script that installs the keepalive. Safe to run again: it rewrites only its own three files.
pub fn script(plan: &KeepalivePlan) -> String {
    format!(
        r##"#!/bin/sh
# DNet Engine endpoint keepalive. Generated by the client; it contains no secret.
# A burst of idle-priority work at intervals, so that an otherwise idle machine is not reclaimed.
set -eu
mkdir -p /opt/dnet/bin

cat > /opt/dnet/bin/dnet-keepalive <<'WORK_EOF'
#!/bin/sh
# Count for BURST seconds, then stop. No network, no disk.
end=$(( $(date +%s) + {burst} ))
while [ "$(date +%s)" -lt "$end" ]; do :; done
WORK_EOF
chmod 0755 /opt/dnet/bin/dnet-keepalive

cat > /etc/systemd/system/dnet-keepalive.service <<'UNIT_EOF'
[Unit]
Description=DNet Engine endpoint keepalive burst
[Service]
Type=oneshot
Nice=19
CPUSchedulingPolicy=idle
ExecStart=/opt/dnet/bin/dnet-keepalive
UNIT_EOF

cat > /etc/systemd/system/dnet-keepalive.timer <<'UNIT_EOF'
[Unit]
Description=DNet Engine endpoint keepalive schedule
[Timer]
OnBootSec=120
OnUnitInactiveSec={period}
[Install]
WantedBy=timers.target
UNIT_EOF

systemctl daemon-reload
systemctl enable --now dnet-keepalive.timer >/dev/null
{check}
"##,
        burst = plan.burst_secs,
        period = plan.period_secs,
        check = CHECK_COMMAND,
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_default_is_a_tenth_of_the_time_and_is_itself_accepted() {
        let plan = KeepalivePlan::default();
        assert_eq!(plan.duty_percent(), 10);
        assert_eq!(
            KeepalivePlan::new(plan.burst_secs(), plan.period_secs()),
            Ok(plan)
        );
    }

    #[test]
    fn schedules_that_would_not_help_or_would_hog_the_machine_are_refused() {
        assert_eq!(
            KeepalivePlan::new(10, 100),
            Err(KeepaliveError::BurstTooShort)
        );
        assert_eq!(
            KeepalivePlan::new(240, 7200),
            Err(KeepaliveError::PeriodTooLong)
        );
        // Too little: 5%.
        assert_eq!(
            KeepalivePlan::new(120, 2400),
            Err(KeepaliveError::DutyOutOfRange)
        );
        // Too much: 60%, and a burst longer than its period.
        assert_eq!(
            KeepalivePlan::new(120, 200),
            Err(KeepaliveError::DutyOutOfRange)
        );
        assert_eq!(
            KeepalivePlan::new(300, 200),
            Err(KeepaliveError::DutyOutOfRange)
        );
        // The edges are in.
        assert!(KeepalivePlan::new(240, 3000).is_ok(), "8%");
        assert!(KeepalivePlan::new(240, 480).is_ok(), "50%");
    }

    #[test]
    fn the_script_schedules_the_burst_and_the_period_it_was_given() {
        let text = script(&KeepalivePlan::new(180, 1800).unwrap());
        assert!(text.contains("+ 180 ))"), "{text}");
        assert!(text.contains("OnUnitInactiveSec=1800"), "{text}");
        assert!(text.starts_with("#!/bin/sh\n"));
        assert!(text.contains("\nset -eu\n"));
    }

    #[test]
    fn the_work_gives_way_to_the_transports_and_touches_neither_network_nor_disk() {
        let text = script(&KeepalivePlan::default());
        assert!(text.contains("Nice=19"));
        assert!(text.contains("CPUSchedulingPolicy=idle"));
        let work = text.split("WORK_EOF").nth(1).unwrap();
        for forbidden in ["curl", "wget", "nc ", "ping", "dd ", ">>", "tee"] {
            assert!(!work.contains(forbidden), "the work uses {forbidden}");
        }
    }

    #[test]
    fn it_is_enabled_and_then_checked_with_the_command_providers_use() {
        let text = script(&KeepalivePlan::default());
        assert!(text.contains("systemctl enable --now dnet-keepalive.timer"));
        assert!(text.trim_end().ends_with(CHECK_COMMAND));
        // A non-zero status stops the script (`set -e`), so the job sees the failure.
    }

    #[test]
    fn it_rewrites_only_its_own_files_and_deletes_nothing() {
        let text = script(&KeepalivePlan::default());
        assert!(!text.contains("rm "));
        let own = [
            "/opt/dnet/bin/dnet-keepalive",
            "/etc/systemd/system/dnet-keepalive.service",
            "/etc/systemd/system/dnet-keepalive.timer",
        ];
        for line in text.lines().filter(|l| l.contains("cat > ")) {
            assert!(own.iter().any(|f| line.contains(f)), "{line}");
        }
    }

    #[test]
    fn the_script_parses_as_shell() {
        let Some(shell) = ["sh", "bash"].into_iter().find(|s| {
            std::process::Command::new(s)
                .arg("-c")
                .arg("exit 0")
                .output()
                .is_ok_and(|o| o.status.success())
        }) else {
            eprintln!("SKIPPED: no shell on this machine to check the script's syntax");
            return;
        };
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("keepalive.sh");
        std::fs::write(&path, script(&KeepalivePlan::default())).unwrap();
        let output = std::process::Command::new(shell)
            .arg("-n")
            .arg(&path)
            .output()
            .unwrap();
        assert!(
            output.status.success(),
            "{}",
            String::from_utf8_lossy(&output.stderr)
        );
    }
}
