//! T189 — keeping a shared server's speed fair between the devices that use it (ADR-0008 "Share a server").
//!
//! A server has one connection to the internet, and every friend's device uses it at once. When one of them
//! downloads something large, the others should still be able to load a page. The one place the server can see
//! them apart is the network card's outgoing queue: each device's carrier is its own connection, so a queue that
//! shares its rate **per connection** gives each device an equal share while the link is busy, and costs nothing
//! while it is not.
//!
//! That only works if the queue is where the waiting happens. A cloud provider limits a machine's speed outside
//! the machine, so the machine's own queue stays empty and nothing is shared. The script therefore limits the card
//! to a rate the owner gives, which should be a little under what the provider allows: then the queue forms here,
//! where it is shared, and not in the provider's network, where it is not.
//!
//! - **One number reaches the script**, an integer in a fixed range. Nothing a person typed is ever put in it.
//! - **It only ever touches the outgoing queue of the card the server reaches the internet by**, and says so. It
//!   changes no firewall rule, no route and nothing of DNet Engine's own.
//! - **It is undone by the other script**, and by `dnet-fairness remove` on the server.
//! - **It survives a reboot**: a small service puts the queue back at start-up.

/// The slowest rate accepted: 1 Mbit/s. Below that the server would be unusable, which is never what was meant.
pub const MIN_MBIT: u32 = 1;
/// The fastest rate accepted: 10 Gbit/s, which no server here has.
pub const MAX_MBIT: u32 = 10_000;

#[derive(Debug, Clone, Copy, PartialEq, Eq, thiserror::Error)]
pub enum FairnessError {
    #[error("the speed must be between {MIN_MBIT} and {MAX_MBIT} megabits a second")]
    Rate,
}

/// The program installed on the server: `apply <mbit>` and `remove`. Plain sh, no input but one integer and the
/// card's own name read from the server's routing table.
const HELPER: &str = r##"#!/bin/sh
# DNet Engine: share this server's speed fairly between the devices that use it.
set -eu
umask 077

nic() {
  # The card the server reaches the internet by: the one the default route leaves through.
  name=$(ip -o -4 route show to default 2>/dev/null | awk '{ for (i = 1; i < NF; i++) if ($i == "dev") { print $(i + 1); exit } }')
  case "$name" in
    ''|*[!A-Za-z0-9_.:@-]*) echo "no network card was found to share the speed of" >&2; return 1 ;;
  esac
  [ "${#name}" -le 32 ] || { echo "the network card's name is not usable" >&2; return 1; }
  printf '%s\n' "$name"
}

case "${1:-}" in
  apply)
    rate="${2:-}"
    case "$rate" in ''|*[!0-9]*) echo "the speed must be a whole number" >&2; exit 2 ;; esac
    [ "${#rate}" -le 5 ] && [ "$rate" -ge @@MIN@@ ] && [ "$rate" -le @@MAX@@ ] \
      || { echo "the speed must be between @@MIN@@ and @@MAX@@ megabits a second" >&2; exit 2; }
    NIC=$(nic) || exit 3
    # Everything leaving the card goes through one class held to the rate, and inside it each connection has its
    # own queue, served in turn.
    tc qdisc replace dev "$NIC" root handle 1: htb default 10
    tc class replace dev "$NIC" parent 1: classid 1:10 htb rate "${rate}mbit" ceil "${rate}mbit" quantum 1514
    tc qdisc replace dev "$NIC" parent 1:10 handle 10: fq_codel
    echo "applied: $NIC, $rate megabits a second shared fairly"
    ;;
  remove)
    NIC=$(nic) || exit 0
    # Only what this program put there: another setup's queue is left alone.
    if tc qdisc show dev "$NIC" 2>/dev/null | grep -q '^qdisc htb 1: root'; then
      tc qdisc del dev "$NIC" root
      echo "removed: $NIC is back to its own queue"
    else
      echo "nothing to remove on $NIC"
    fi
    ;;
  *)
    echo "usage: dnet-fairness <apply <megabits>|remove>" >&2
    exit 2
    ;;
esac
"##;

/// The helper program, with the accepted range filled in.
#[must_use]
pub fn helper() -> String {
    HELPER
        .replace("@@MIN@@", &MIN_MBIT.to_string())
        .replace("@@MAX@@", &MAX_MBIT.to_string())
}

/// The head every fairness script shares: root, the tools, the helper installed.
fn head(what: &str) -> String {
    format!(
        r##"#!/bin/sh
# DNet Engine: {what}. Generated by the client; it holds no secret.
set -eu
umask 077
BIN=/opt/dnet/bin
[ "$(id -u)" = 0 ] || {{ echo "run this as root: put sudo in front of it, or log in as root" >&2; exit 2; }}
command -v tc >/dev/null 2>&1 || {{ echo "the tc program is needed on this server (the package is called iproute2)" >&2; exit 2; }}
command -v systemctl >/dev/null 2>&1 || {{ echo "this server does not use systemd, which this script needs" >&2; exit 2; }}
mkdir -p "$BIN"
chmod 755 /opt/dnet "$BIN" 2>/dev/null || true
cat > "$BIN/dnet-fairness" <<'FAIRNESS_EOF'
{helper}
FAIRNESS_EOF
chmod 755 "$BIN/dnet-fairness"
"##,
        helper = helper().trim_end()
    )
}

/// The script that turns fair sharing on at `mbit` megabits a second, now and at every start-up.
pub fn fairness_script(mbit: u32) -> Result<String, FairnessError> {
    if !(MIN_MBIT..=MAX_MBIT).contains(&mbit) {
        return Err(FairnessError::Rate);
    }
    Ok(format!(
        r##"{head}
cat > /etc/systemd/system/dnet-fairness.service <<'UNIT_EOF'
[Unit]
Description=DNet Engine: share this server's speed fairly between devices
After=network-online.target
Wants=network-online.target

[Service]
Type=oneshot
RemainAfterExit=yes
ExecStart=/opt/dnet/bin/dnet-fairness apply {mbit}
ExecStop=/opt/dnet/bin/dnet-fairness remove

[Install]
WantedBy=multi-user.target
UNIT_EOF
systemctl daemon-reload
systemctl enable dnet-fairness.service >/dev/null 2>&1
systemctl restart dnet-fairness.service
# Say what is there now, so what was done can be seen.
"$BIN/dnet-fairness" apply {mbit}
echo "done. Turn it off again with the other script from DNet Engine."
"##,
        head = head("share the speed fairly between devices"),
    ))
}

/// The script that takes fair sharing off again and leaves the card's queue as it was.
#[must_use]
pub fn fairness_off_script() -> String {
    format!(
        r##"{head}
systemctl disable --now dnet-fairness.service >/dev/null 2>&1 || true
rm -f /etc/systemd/system/dnet-fairness.service
systemctl daemon-reload
"$BIN/dnet-fairness" remove
echo "done."
"##,
        head = head("stop sharing the speed between devices"),
    )
}

